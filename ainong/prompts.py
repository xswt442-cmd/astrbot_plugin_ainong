"""给模型的三段提示词。

放在这里而不是 `main.py`：`main.py` 顶层 import astrbot，本地跑不了单测，而
提示词里那些**硬性的输出格式与反端水约定**是要被测试钉住的。

三条约定写在提示里，也写在测试里：

1. **称号那一行必须以「你最近是个」开头**，模型很爱自由发挥成「称号：xxx」。
2. **PK 的对比由代码算好再交给模型**（见 `stats.对比要点`）。让模型自己比，它
   最省事的答案就是「各有千秋」——实测产出的 83 对 87 完全看不出输赢。所以提示
   里明确写死「不许推翻对比结论」，并把端水词列成禁令。
3. **只说数据支撑得住的话。** 编出来的分析看起来很有道理，用户分辨不出来还会
   照着改，比没有分析更糟。
"""

from __future__ import annotations

__all__ = ["称号前缀", "端水词", "推演声明", "锐评提示", "开一局提示", "PK提示"]

# 称号那一行必须这么开头。提示词里写一遍，测试里再钉一遍。
称号前缀 = "你最近是个"

# 「开一局」的免责行。用户必须一眼看出这不是真实战绩，所以写死在提示里，
# 输出时要原样带出来。
推演声明 = "⚠️ 这局是推演出来的，不是真实战绩"

# 反端水禁令。列出来比说「不要端水」有效——模型对具体词表最敏感。
端水词 = (
    "各有千秋",
    "不相上下",
    "势均力敌",
    "难分伯仲",
    "都很强",
    "继续努力",
    "加油",
    "都有提升空间",
    "提升空间很大",
)

_锐评骨架 = f"""\
{称号前缀}<称号>

<两三句总评：这份数据说明了什么>

打得好：<点到具体英雄与数据，说清他真正靠什么赢>
问题：<点出数据里最扎眼的一处短板>
建议：<一条今天就能照做的具体做法>"""


def 锐评提示(数据: str) -> str:
    """锐评的提示词。数据是 `ainong.stats.汇总文本` 的输出。"""
    return (
        "下面是一个玩家自己的王者荣耀近期战绩统计。请写一段锐评，"
        "严格按下面的格式输出，不要前言、不要标题、不要编号：\n\n"
        f"{_锐评骨架}\n\n"
        "硬要求：\n"
        f"- 第一行必须以「{称号前缀}」开头，后面接不超过 18 字的称号；称号里要带上"
        "他的段位或招牌英雄，例如「你最近是个星耀局靠牛魔吃红利的团队工具人」。\n"
        "- 称号要贴着数据说，别写成「发挥出色」这类放在谁身上都成立的废话。\n"
        "- 后面三个小标题原样保留（打得好／问题／建议），每段一句话。\n"
        "- 全文至少出现 3 个具体数字（胜率、KDA、MVP 次数、连胜之类），"
        "不许通篇形容词。\n"
        "- 「问题」那一段必须指向数据里的具体一项；"
        "不许写「多注意意识」「多练英雄」这种没落到数据上的话。\n"
        "- **只说数据支撑得住的话**。数据里没有的依据不要编：没给对局明细就"
        "不许分析某一场的具体经过，没给经济与伤害就不许讲「前期没打出优势」。"
        "宁可少说一句，也不要编一句——编出来的分析看起来很有道理。\n"
        f"- 禁止出现这些端水词：{'、'.join(端水词)}。\n"
        "- 不要复述数据原文，不要「首先／其次／总而言之」，不要客套。\n"
        "- 全文 180 到 260 字。\n\n"
        "数据：\n"
        f"{数据}"
    )


_一局骨架 = """\
选人：<英雄（位置）>
经过：<两三句：这一局是怎么打的，节奏怎么走>
亮点：<点出这局最漂亮的一处，带具体数字>
问题：<点出这局最难看的一处，带具体数字>
复盘：<一句下次该怎么做>
结算：{结果} ｜ <击杀>/<死亡>/<助攻> ｜ 评分 <x.x>"""


def 开一局提示(数据: str, 结果: str) -> str:
    """推演一局的提示词。`结果` 由 `stats.抽对局结果` 按真实胜率抽好。"""
    return (
        "下面是一个玩家自己的王者荣耀近期战绩。假设他刚刚又开了一局排位，"
        f"这局的**胜负已经定了：{结果}**，请你推演出这一局的过程与结果。\n\n"
        "严格按下面的格式输出，不要前言、不要标题、不要编号：\n\n"
        f"{推演声明}\n"
        f"{_一局骨架.format(结果=结果)}\n\n"
        "硬要求：\n"
        f"- 第一行必须是「{推演声明}」，原样保留，不许改写、不许省略。\n"
        "- 后面六个标签原样保留（选人／经过／亮点／问题／复盘／结算），"
        "经过两到三句，其余各一到两句。\n"
        "- 选人必须从他「常用英雄」里挑一个，位置要跟这个英雄对得上，不要编别的英雄。\n"
        "- 「经过」每段带一个具体细节（时间点、装备、关键团战或技能），"
        "不要写「打得很稳」这种没画面的话。\n"
        "- 「亮点」和「问题」各必须带上一个具体数字。\n"
        f"- 结算那行的胜负必须原样写「{结果}」，不许改；"
        "KDA 与评分要跟他平时的水平对得上（参考上面的场均与平均评分），"
        "别写出一局 20 杀。\n"
        "- **只说数据支撑得住的话**。没给的维度不要编，"
        "宁可少说一句，也不要编一句。\n"
        "- 不要复述数据原文，不要「首先／其次／总而言之」，不要客套。\n"
        "- 全文 240 字以内。\n\n"
        "数据：\n"
        f"{数据}"
    )


def PK提示(
    甲名: str,
    乙名: str,
    对比: str,
    占优: str,
    甲数据: str,
    乙数据: str,
) -> str:
    """两人 PK 的提示词。

    `对比` 与 `占优` 都由 `stats.对比要点` 算好——模型不做比较，只做解说。
    """
    return (
        f"下面是 {甲名} 和 {乙名} 的王者荣耀近期战绩。逐项对比**已经替你算好了**，"
        "你的任务只是解说和打分：不要重算、不要推翻对比结论、不要两边都给好评。\n\n"
        "严格按下面的格式输出，不要前言、不要标题、不要编号：\n\n"
        f"{甲名} <分数>\n"
        f"{乙名} <分数>\n"
        "胜者：<名字>\n"
        "逐项：<挑差异最大的 3 项，写成「项名：谁占优（谁的数字 对 谁的数字）」>\n"
        "互损：<两三句>\n\n"
        "硬要求：\n"
        "- 分数取 0-100 的整数，分差要跟两人的实际差距相符。"
        "两人本来就接近时不必为了制造对立拉开分数。\n"
        "- 胜者那一行写分数更高的那个人，名字从这里挑："
        f"{甲名} 或 {乙名}。\n"
        "- 占优项更多的一方不一定分数更高，一切从实际出发。"
        f"占优项数仅供参考：{占优}\n"
        "- 「逐项」那行必须写出项名与双方数字。\n"
        "- 「互损」必须点名双方最难看的那一项，带上具体数字或英雄名，"
        "对于输的一方点名更狠一点。\n"
        "- **只说数据支撑得住的话**。数据里没有的依据不要编，"
        "宁可少说一句，也不要编一句。\n"
        f"- 禁止出现这些端水词：{'、'.join(端水词)}。\n"
        "- 「互损」至少 90 字，不许一句话打发。\n"
        "- 不要复述数据原文，不要「首先／其次／总而言之」。\n\n"
        "已算好的逐项对比：\n"
        f"{对比}\n\n"
        f"【{甲名}】原始数据\n{甲数据}\n\n【{乙名}】原始数据\n{乙数据}"
    )
